% plot_Fig2c_heatmap
% Recreates Fig. 2c heatmaps from processed plotting matrices.

clear;
close all;

scriptDir = fileparts(mfilename('fullpath'));
rootDir = fileparts(fileparts(scriptDir));
dataFile = fullfile(rootDir, 'data', 'Fig2', 'Fig2c_heatmap_plot_data.mat');
resultDir = fullfile(rootDir, 'results', 'Fig2');

if ~exist(resultDir, 'dir')
    mkdir(resultDir);
end

S = load(dataFile, 'plot_data');
plot_data = S.plot_data;

fig = figure('Color', 'w', 'Units', 'centimeters', 'Position', [2 2 14.6 5.2]);
colormap(fig, rdYlBuBlueWhiteRed(256));

lefts = [0.055, 0.345, 0.635];
axWidth = 0.245;
axHeight = 0.79;
bottom = 0.11;

axesList = gobjects(1, 3);
for i = 1:3
    hm = plot_data.heatmaps(i);
    ax = axes(fig, 'Position', [lefts(i), bottom, axWidth, axHeight]);
    axesList(i) = ax;
    imagesc(ax, hm.time_s, 1:hm.n_rows, hm.matrix_percent);
    clim(ax, plot_data.clim_percent);
    xlim(ax, plot_data.xlim_s);
    ylim(ax, [0.5, hm.n_rows + 0.5]);
    set(ax, 'YDir', 'reverse', 'YTick', [], 'XTick', plot_data.xticks_s, ...
        'FontName', 'Arial', 'FontSize', 10, 'LineWidth', 1.0, ...
        'TickDir', 'out', 'Box', 'off', 'Layer', 'top');

    hold(ax, 'on');
    rectangle(ax, 'Position', [plot_data.xlim_s(1), 0.5, ...
        diff(plot_data.xlim_s), hm.n_rows], 'EdgeColor', 'k', 'LineWidth', 1.0);

    xNorm1 = lefts(i) + (plot_data.activation_window_s(1) - plot_data.xlim_s(1)) / diff(plot_data.xlim_s) * axWidth;
    xNorm2 = lefts(i) + (plot_data.activation_window_s(2) - plot_data.xlim_s(1)) / diff(plot_data.xlim_s) * axWidth;
    annotation(fig, 'rectangle', [xNorm1, bottom + axHeight + 0.018, xNorm2 - xNorm1, 0.035], ...
        'FaceColor', [205 235 193] / 255, 'EdgeColor', 'none');
end

cb = colorbar(axesList(3), 'Location', 'eastoutside');
cb.Position = [0.905, bottom + 0.07, 0.022, 0.30];
cb.Ticks = plot_data.clim_percent;
cb.TickLabels = {'0', '40'};
cb.FontName = 'Arial';
cb.FontSize = 10;
cb.LineWidth = 0.8;
cb.Label.String = '\DeltaF/F_0 (%)';
cb.Label.FontName = 'Arial';
cb.Label.FontSize = 11;
cb.Label.Rotation = 90;
cb.Label.Units = 'normalized';
cb.Label.Position = [2.45, 0.5, 0];

outPng = fullfile(resultDir, 'Fig2c_heatmap.png');
outPdf = fullfile(resultDir, 'Fig2c_heatmap.pdf');

if exist('exportgraphics', 'file') == 2
    exportgraphics(fig, outPng, 'Resolution', 600);
    exportgraphics(fig, outPdf, 'ContentType', 'vector');
else
    print(fig, outPng, '-dpng', '-r600');
    print(fig, outPdf, '-dpdf', '-painters');
end

close(fig);

